"""样式字面量检查（docs/conventions/ui.md 规则 1）的反例；反例只在内存与临时目录中构造，不进仓库。"""
import unittest

from _support import ROOT, load_engineering, temp_repo, write

style = load_engineering("check_style_literals")


def msgs(rel, text):
    return [m for _, _, m in style.check_text(rel, text)]


class StyleLiteralsTest(unittest.TestCase):
    def test_css_literals(self):
        """CSS 中的十六进制色值、非零像素与颜色函数字面量被拦下，var() 与 0 不拦"""
        found = msgs("apps/learner/src/a.css", ".a { color: #fff; margin: 12px; background: rgb(0 0 0 / 0.5); }\n"
                                               ".b { color: var(--color-ink-primary); margin: 0px; }\n")
        self.assertEqual(len(found), 3, found)

    def test_classname_arbitrary_values(self):
        """className 里的 Tailwind 任意值（色值、像素）与默认调色板类被拦下"""
        found = msgs("apps/learner/src/A.tsx", 'export const A = () => <div className="bg-[#9fd3b4] w-[13px] text-red-500 bg-white" />;\n')
        self.assertEqual(len(found), 4, found)

    def test_style_object(self):
        """style 对象里的尺寸数字与色值被拦下"""
        found = msgs("packages/ui/src/B.tsx", 'export const B = () => <div style={{ width: 13, flex: 1, color: "#000" }} />;\n')
        self.assertEqual(len(found), 2, found)

    def test_style_object_with_url(self):
        """style 对象中的 URL 字符串不被当成注释，前后的尺寸数字仍被拦下"""
        for body in ('width: 13, backgroundImage: "url(https://a.test/x.png)"',
                     'backgroundImage: "url(https://a.test/x.png)", width: 13'):
            with self.subTest(body=body):
                found = msgs("packages/ui/src/B.tsx", 'export const B = () => <div style={{ ' + body + ' }} />;\n')
                self.assertEqual(found, ["style 对象的尺寸数字 width: 13（数字按像素解释）"])
        self.assertEqual(msgs("packages/ui/src/B.tsx", 'export const B = () => <div style={{ backgroundImage: "url(https://a.test/x.png)" }} />;\n'), [])

    def test_token_classes_pass(self):
        """登记的令牌类与 var() 引用通过"""
        self.assertEqual(msgs("apps/learner/src/C.tsx", 'export const C = () => <main className="bg-bg-canvas text-ink-primary rounded-md text-title" />;\n'), [])

    def test_generated_and_exempt(self):
        """生成物与写明 style-exempt 理由的行不拦"""
        self.assertEqual(msgs("packages/ui/src/generated/tokens.css", "/* GENERATED by spec_tool gen */\n:root { --x: #fff; }\n"), [])
        self.assertEqual(msgs("apps/learner/index.html", '<meta name="theme-color" content="#2E4A8E" /> <!-- style-exempt: 浏览器主题色只认字面值 -->\n'), [])

    def test_comments_ignored(self):
        """注释中的色值不拦"""
        self.assertEqual(msgs("apps/learner/src/D.ts", "// 反例：#9fd3b4 与 13px\nexport const d = 1;\n"), [])

    def test_scan_counterexample_file(self):
        """扫描目录时拦下反例文件，生成物目录不扫描"""
        root = temp_repo(self)
        write(root, "apps/learner/src/bad.css", ".x { padding: 7px; }\n")
        write(root, "packages/ui/src/generated/tokens.css", ":root { --x: 7px; }\n")
        found = style.scan(root)
        self.assertEqual([(r, ln) for r, ln, _ in found], [("apps/learner/src/bad.css", 1)])

    def test_repo_passes(self):
        """仓库当前的界面代码通过样式字面量检查"""
        self.assertEqual(style.scan(ROOT), [])


if __name__ == "__main__":
    unittest.main()
