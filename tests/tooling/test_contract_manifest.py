"""接口生成物（计划 C6）：manifest.json 检出缺失、过期、多余与手改；源哈希在 Python 与 contract-gen.mjs 两侧一致。"""
import json
import shutil
import subprocess
import unittest

from _support import ROOT, spec_tool, temp_repo, write

DIR = spec_tool.CFG["gen"]["contract_dir"]
SOURCES = spec_tool.CFG["gen"]["contract_sources"]


class ContractManifestTest(unittest.TestCase):
    def make(self):
        root = temp_repo(self)
        for s in SOURCES:
            write(root, s, f"// {s}\r\nsource\n")
        src = spec_tool.short_hash("".join(spec_tool.read_text(root / s) for s in SOURCES))
        files = {}
        for name in ("endpoints.ts", "endpoints.zod.ts"):
            text = f"// GENERATED by spec_tool gen（Orval），source-sha: {src}\nexport const x = 1;\n"
            write(root, f"{DIR}/{name}", text)
            files[name] = spec_tool.short_hash(text)
        write(root, f"{DIR}/manifest.json", json.dumps({"source_sha": src, "files": files}))
        return root

    def codes(self, root):
        return [(f.code, f.file.rsplit("/", 1)[-1]) for f in spec_tool.contract_findings(spec_tool.Repo(root))]

    def test_consistent(self):
        """接口生成物与清单一致时没有问题"""
        self.assertEqual(self.codes(self.make()), [])

    def test_missing(self):
        """接口生成物缺失（没有清单或清单列出的文件不在）报 E-GEN-01"""
        root = self.make()
        (root / DIR / "endpoints.zod.ts").unlink()
        self.assertEqual(self.codes(root), [("E-GEN-01", "endpoints.zod.ts")])
        shutil.rmtree(root / DIR)
        self.assertEqual(self.codes(root), [("E-GEN-01", "manifest.json")])

    def test_hand_edit(self):
        """手改接口生成物报 E-GEN-02"""
        root = self.make()
        p = root / DIR / "endpoints.ts"
        p.write_text(p.read_text(encoding="utf-8") + "export const y = 2;\n", encoding="utf-8")
        self.assertEqual(self.codes(root), [("E-GEN-02", "endpoints.ts")])

    def test_stale_and_extra(self):
        """源改动后报过期，清单外的多余文件报 E-GEN-01"""
        root = self.make()
        write(root, SOURCES[0], "changed\n")
        self.assertEqual(self.codes(root), [("E-GEN-01", "manifest.json")])
        root = self.make()
        write(root, f"{DIR}/extra.ts", "export {};\n")
        self.assertEqual(self.codes(root), [("E-GEN-01", "extra.ts")])

    def test_source_sha_matches_node(self):
        """清单的源哈希在 Python（spec_tool）与 Node（contract-gen.mjs）两侧算法一致"""
        node = shutil.which("node")
        self.assertIsNotNone(node, "需要 node（工程脚本由 Node 24 运行）")
        out = subprocess.run([node, str(ROOT / "scripts/engineering/contract-gen.mjs"), "--print-source-sha"],
                             capture_output=True, text=True, check=True).stdout.strip()
        want = spec_tool.short_hash("".join(spec_tool.read_text(ROOT / s) for s in SOURCES if (ROOT / s).exists()))
        self.assertEqual(out, want)


if __name__ == "__main__":
    unittest.main()
