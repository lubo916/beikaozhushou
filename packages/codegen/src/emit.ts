// 生成物的公共写法：生成物头、来源哈希与字面量（字符串与键用 JSON 写法，数字按 YAML 原文区分整数与小数）。
import { createHash } from "node:crypto";
import { Num, type YamlValue } from "./yaml.ts";

export const MARK = "GENERATED by pnpm gen";

export function normalize(text: string): string {
  return text.replace(/\r\n?/g, "\n");
}

/** 12 位短哈希（与 V3 的 source-sha 同算法：换行统一为 \n 后取 SHA-256 前 12 位）。 */
export function sha12(text: string): string {
  return createHash("sha256").update(normalize(text), "utf8").digest("hex").slice(0, 12);
}

/** TS 生成物的文件头：来源、来源哈希与一句说明。 */
export function header(sources: string, sha: string, note: string): string {
  return `// ${MARK}（packages/codegen），来源：${sources}；勿手改。source-sha: ${sha}\n// ${note}\n\n`;
}

function formatNum(n: Num): string {
  if (n.integer) return String(n.value);
  return Number.isInteger(n.value) ? n.value.toFixed(1) : String(n.value);
}

/** YAML 值 → TS 字面量（对象写成 { "键": 值 }，空对象为 {  }，与 V3 生成物一致）。 */
export function literal(value: YamlValue): string {
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "boolean") return String(value);
  if (value instanceof Num) return formatNum(value);
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`;
  const items = Object.entries(value).map(([k, v]) => `${JSON.stringify(k)}: ${literal(v)}`);
  return `{ ${items.join(", ")} }`;
}
