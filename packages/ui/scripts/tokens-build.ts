// 设计令牌 → CSS（F03 定的生成方式）：design/tokens.json（DTCG）与 tokens.resolver.json 生成
// packages/ui/src/generated/tokens.css（CSS 变量：基础值在 :root，修饰器按 data-* 属性覆盖）与 tailwind-theme.css（Tailwind 4 主题映射）。
// 纯函数：输入是解析后的 JSON，输出两个文件的文本；读写文件在 gen-tokens.ts。

export type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

export interface Token {
  readonly path: readonly string[];
  readonly value: Json;
}

export interface TokenOutputs {
  readonly tokensCss: string;
  readonly tailwindCss: string;
}

const SOURCES = "design/tokens.json、design/tokens.resolver.json";
const GENERATOR = "packages/ui/scripts/gen-tokens.ts";

function isObject(value: Json | undefined): value is { [key: string]: Json } {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** 展开 DTCG 树：带 $value 的节点是令牌，$ 开头的键是元数据。 */
export function flattenTokens(tree: Json, path: readonly string[] = []): Token[] {
  if (!isObject(tree)) return [];
  if ("$value" in tree) return [{ path, value: tree["$value"] ?? null }];
  return Object.entries(tree)
    .filter(([key]) => !key.startsWith("$"))
    .flatMap(([key, child]) => flattenTokens(child, [...path, key]));
}

const varName = (path: readonly string[]) => `--${path.join("-")}`;

/** 令牌值 → CSS 值；引用 {a.b} 写成 var(--a-b)，引用不到的返回 null（运行时才知道，构建时跳过）。 */
export function cssValue(value: Json, known: ReadonlySet<string>): string | null {
  if (typeof value === "string") {
    const ref = /^\{([^}]+)\}$/.exec(value);
    if (!ref) return value;
    const name = varName((ref[1] ?? "").split("."));
    return known.has(name) ? `var(${name})` : null;
  }
  if (typeof value === "number") return String(value);
  if (Array.isArray(value)) return value.map((v) => (typeof v === "string" && /\s/.test(v) ? `"${v}"` : String(v))).join(", ");
  if (isObject(value) && typeof value["value"] === "number" && typeof value["unit"] === "string")
    return `${value["value"]}${value["unit"]}`;
  return null;
}

/** 令牌路径 → Tailwind 4 主题变量名；不进主题的返回 null。断点单独处理（容器查询只能写字面值）。 */
export function tailwindName(path: readonly string[]): string | null {
  const [group, kind, ...rest] = path;
  const tail = rest.join("-");
  if (group === "color" || group === "radius") return varName(path);
  if (group === "font" && kind === "family") return `--font-${tail}`;
  if (group === "font" && kind === "size") return `--text-${tail}`;
  if (group === "font" && kind === "line-height") return `--leading-${tail}`;
  if (group === "font" && kind === "weight") return `--font-weight-${tail}`;
  if (group === "size" && kind === "space") return `--spacing-${tail}`;
  return null;
}

interface Modifier {
  readonly name: string;
  readonly default: string;
  readonly contexts: Record<string, Json[]>;
}

/** 生成两个 CSS 文件的文本。sourceSha 是来源文件的摘要（写进文件头，便于发现手改）。 */
export function buildTokenCss(tokens: Json, resolver: Json, sourceSha: string): TokenOutputs {
  const base = flattenTokens(tokens);
  const known = new Set(base.map((t) => varName(t.path)));
  const decl = (t: Token) => {
    const v = cssValue(t.value, known);
    return v === null ? null : `  ${varName(t.path)}: ${v};`;
  };
  const blocks = [`:root {\n${base.map(decl).filter(Boolean).join("\n")}\n}`];
  const skipped: string[] = [];
  const modifiers = (isObject(resolver) && Array.isArray(resolver["modifiers"]) ? resolver["modifiers"] : []) as unknown as Modifier[];
  for (const mod of modifiers) {
    for (const [context, sets] of Object.entries(mod.contexts)) {
      if (context === mod.default || sets.length === 0) continue;
      const items = sets.flatMap((set) => flattenTokens(set));
      const lines = items.map(decl);
      if (lines.some((line) => line === null)) {
        skipped.push(`${mod.name}.${context}`);
        continue;
      }
      blocks.push(`:root[data-${mod.name}="${context}"] {\n${lines.join("\n")}\n}`);
    }
  }
  const head = `/* GENERATED by ${GENERATOR}，来源：${SOURCES}；勿手改（改令牌后运行 node ${GENERATOR}）。source-sha: ${sourceSha} */`;
  const note = `/* 基础值在外壳根元素（:root）上，修饰器按其 data-<修饰器名> 属性覆盖。${skipped.length ? `构建时跳过的上下文：${skipped.join("、")}（依赖运行时配置）。` : ""} */`;
  const tokensCss = `${head}\n${note}\n\n${blocks.join("\n\n")}\n`;

  const containers = base
    .filter((t) => t.path[0] === "size" && t.path[1] === "breakpoint")
    .map((t) => `  --container-${t.path.slice(2).join("-")}: ${cssValue(t.value, known)};`);
  const mapped = base.flatMap((t) => {
    const name = tailwindName(t.path);
    return name === null ? [] : [`  ${name}: var(${varName(t.path)});`];
  });
  const twNote =
    "/* Tailwind 4 主题：先清空默认主题（调色板、间距、断点等），再把令牌变量映射为主题变量，界面只能用登记的令牌类；间距用 size.space 阶梯（p-1 … p-12）；容器断点用于容器查询，只能写字面值。 */";
  const tailwindCss = `${head.replace("勿手改", "映射规则在 packages/ui/scripts/tokens-build.ts；勿手改")}\n${twNote}\n\n@theme {\n  --*: initial;\n${containers.join("\n")}\n}\n\n@theme inline {\n${mapped.join("\n")}\n}\n`;
  return { tokensCss, tailwindCss };
}
