#!/usr/bin/env node
// 接口生成物（0.1b 计划 C6）：由 contracts/openapi.yaml 经 Orval（orval.config.ts）生成钩子、类型、Zod 结构与 MSW 模拟，
// 写入 packages/contract/src/generated/api/：每个文件加 spec_tool 的生成物头，并写 manifest.json（源哈希与各文件哈希），
// spec_tool gen --check 据此检出缺失、过期与手改（不需要安装依赖）。
// 用法：node scripts/engineering/contract-gen.mjs            重新生成
//       node scripts/engineering/contract-gen.mjs --check    原位重新生成后与现有文件比对，再恢复原状；不一致时退出码 1
//       node scripts/engineering/contract-gen.mjs --print-source-sha
// SOURCES 与 scripts/spec_tool.toml 的 [gen].contract_sources 保持一致；哈希算法与 spec_tool 的 short_hash 相同（换行统一为 \n）。
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT_REL = "packages/contract/src/generated/api";
const OUT = join(ROOT, OUT_REL);
const SOURCES = ["contracts/openapi.yaml", "orval.config.ts", "scripts/engineering/contract-gen.mjs"];
const MARK = "GENERATED by spec_tool gen";
const HEADER_EXT = /\.(?:ts|tsx|js|mjs)$/;

const normalize = (text) => text.replace(/\r\n?/g, "\n");
const sha12 = (text) => createHash("sha256").update(text, "utf8").digest("hex").slice(0, 12);

export function sourceSha(root = ROOT) {
  return sha12(
    SOURCES.filter((p) => existsSync(join(root, p)))
      .map((p) => normalize(readFileSync(join(root, p), "utf8")))
      .join(""),
  );
}

function listFiles(dir, prefix = "") {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listFiles(join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out.sort();
}

function runOrval() {
  rmSync(OUT, { recursive: true, force: true });
  const r = spawnSync("pnpm", ["exec", "orval", "--config", "orval.config.ts"], {
    cwd: ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (r.status !== 0) throw new Error(`orval 失败（退出码 ${r.status ?? r.signal}）`);
}

function stamp() {
  const src = sourceSha();
  const files = {};
  for (const rel of listFiles(OUT)) {
    if (rel === "manifest.json") continue;
    const p = join(OUT, rel);
    let text = normalize(readFileSync(p, "utf8"));
    if (HEADER_EXT.test(rel) && !text.startsWith(`// ${MARK}`)) {
      text = `// ${MARK}（Orval，经 pnpm contract:gen），来源：contracts/openapi.yaml；勿手改。source-sha: ${src}\n${text}`;
    }
    writeFileSync(p, text);
    files[rel] = sha12(text);
  }
  const manifest = { generator: "orval（scripts/engineering/contract-gen.mjs）", source_sha: src, files };
  writeFileSync(join(OUT, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
}

function snapshot() {
  if (!existsSync(OUT)) return null;
  const dir = mkdtempSync(join(tmpdir(), "exam-prep-contract-"));
  cpSync(OUT, dir, { recursive: true });
  return dir;
}

function restore(dir) {
  rmSync(OUT, { recursive: true, force: true });
  if (dir) {
    cpSync(dir, OUT, { recursive: true });
    rmSync(dir, { recursive: true, force: true });
  }
}

function compare(beforeDir) {
  const before = beforeDir ? listFiles(beforeDir) : [];
  const after = listFiles(OUT);
  const diffs = [];
  for (const f of after) {
    if (!before.includes(f)) diffs.push(`缺失：${OUT_REL}/${f}`);
    else if (normalize(readFileSync(join(beforeDir, f), "utf8")) !== normalize(readFileSync(join(OUT, f), "utf8")))
      diffs.push(`与重新生成的结果不同：${OUT_REL}/${f}`);
  }
  for (const f of before) if (!after.includes(f)) diffs.push(`多余：${OUT_REL}/${f}`);
  return diffs;
}

function main(argv) {
  if (argv.includes("--print-source-sha")) {
    process.stdout.write(`${sourceSha()}\n`);
    return 0;
  }
  if (!argv.includes("--check")) {
    runOrval();
    stamp();
    process.stdout.write(`接口生成物已写入 ${OUT_REL}\n`);
    return 0;
  }
  const before = snapshot();
  let diffs;
  try {
    runOrval();
    stamp();
    diffs = compare(before);
  } finally {
    restore(before);
  }
  for (const d of diffs) process.stdout.write(`✗ ${d}\n`);
  process.stdout.write(
    diffs.length ? `接口生成物漂移：${diffs.length} 处；运行 pnpm contract:gen 后提交。\n` : "接口生成物与 contracts/openapi.yaml 一致。\n",
  );
  return diffs.length ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
