// 词汇常量生成器（F03）：docs/product/glossary.yaml → packages/shared/src/vocab/glossary.generated.ts。
// 用法：node tools/gen-vocab.ts [--check]；--check 只比对、不写盘，不一致时退出码 1（pnpm test 里由 packages/ui/scripts/repo-guards.test.ts 运行）。
// YAML 解析复用 packages/codegen 的解析器；生成物带 GENERATED 标记与来源摘要，ESLint 与 Prettier 跳过 *.generated.*。
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseYaml, plain } from "../packages/codegen/src/yaml.ts";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const SOURCE = "docs/product/glossary.yaml";
const TARGET = "packages/shared/src/vocab/glossary.generated.ts";

interface GlossaryValue {
  readonly label: string | number;
  readonly code?: string;
  readonly rank?: number;
}

interface GlossaryEntry {
  readonly term: string;
  readonly code: string;
  readonly values?: readonly GlossaryValue[];
  readonly forbidden?: readonly string[];
  readonly category?: string;
}

const str = (value: string | number) => JSON.stringify(String(value));
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

function render(entries: readonly GlossaryEntry[], sha: string): string {
  const coded = entries.filter((e) => e.values?.length && e.values.every((v) => typeof v.code === "string"));
  const ranked = coded.filter((e) => e.values?.every((v) => typeof v.rank === "number"));
  const scales = entries.filter((e) => e.values?.length && e.values.every((v) => v.code === undefined));
  const banned = entries.filter((e) => e.category === "banned_copy").flatMap((e) => e.forbidden ?? []);
  const synonyms = entries.filter((e) => e.category !== "banned_copy").flatMap((e) => (e.forbidden ?? []).map((w) => [w, e.term] as const));
  const values = (e: GlossaryEntry, pick: (v: GlossaryValue) => string) => (e.values ?? []).map(pick).join(", ");
  return [
    `// GENERATED by tools/gen-vocab.ts，来源 ${SOURCE}；勿手改（改术语表后运行 node tools/gen-vocab.ts）。source-sha: ${sha}`,
    "// 术语的唯一来源是 docs/product/glossary.yaml（vocabulary.md 是给人看的摘要）；代码与文案只用这里的叫法。",
    "",
    "/** 术语：代码标识 → 叫法。 */",
    "export const TERM = {",
    ...entries.map((e) => `  ${key(e.code)}: ${str(e.term)},`),
    "} as const;",
    "",
    "/** 枚举取值：术语代码 → 取值代码 → 界面叫法（界面文字与代码标识一一对应）。 */",
    "export const VOCAB = {",
    ...coded.map((e) => `  ${key(e.code)}: { ${values(e, (v) => `${key(String(v.code))}: ${str(v.label)}`)} },`),
    "} as const;",
    "",
    "/** 带序号的取值（掌握档 0–5、题目可信度一至四级等）：术语代码 → 取值代码 → 序号。 */",
    "export const RANK = {",
    ...ranked.map((e) => `  ${key(e.code)}: { ${values(e, (v) => `${key(String(v.code))}: ${Number(v.rank)}`)} },`),
    "} as const;",
    "",
    "/** 只有叫法、没有代码标识的取值（如重要度 1–4 级），按术语表顺序。 */",
    "export const SCALE = {",
    ...scales.map((e) => `  ${key(e.code)}: [${values(e, (v) => str(v.label))}],`),
    "} as const;",
    "",
    "/** 禁用同义词：禁用的说法 → 应改用的叫法。 */",
    "export const FORBIDDEN_SYNONYMS = {",
    ...synonyms.map(([word, term]) => `  ${str(word)}: ${str(term)},`),
    "} as const;",
    "",
    "/** 宣传禁用语：任何界面与宣传文案都不出现。 */",
    `export const BANNED_COPY = [${banned.map(str).join(", ")}] as const;`,
    "",
  ].join("\n");
}

const text = readFileSync(ROOT + SOURCE, "utf8");
const entries = plain(parseYaml(text, SOURCE)) as GlossaryEntry[];
const next = render(entries, createHash("sha256").update(text).digest("hex").slice(0, 12));
let current: string;
try {
  current = readFileSync(ROOT + TARGET, "utf8");
} catch {
  current = "";
}
if (current === next) {
  process.stdout.write("词汇常量：已是最新\n");
} else if (process.argv.includes("--check")) {
  process.stdout.write(`✗ ${TARGET} 与 ${SOURCE} 不一致：运行 node tools/gen-vocab.ts\n`);
  process.exitCode = 1;
} else {
  writeFileSync(ROOT + TARGET, next);
  process.stdout.write(`✓ 词汇常量：已更新 ${TARGET}\n`);
}
